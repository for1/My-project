"""FBX ASCII 7.4 导出器（手写，零依赖）。

目标软件：3ds Max、Maya、Blender、UE、Unity、Cinema 4D、Modo。
FBX 是 DCC 里最通用的交换格式，本模块输出 **ASCII 7400**（无需 FBX SDK）：

    * 每个材质一个 Mesh Geometry + 一个 Model，二者用 Connections 挂到场景根。
    * 法线按 PolygonVertex 直接给出，保证墙面是硬边。
    * GlobalSettings 声明 Z 轴向上、单位 = 厘米（FBX 的标准内定单位），
      因此坐标做了 ×100 换算，这样导入 Max/Maya/Blender 后尺寸就是真实米数。

说明：ASCII FBX 不是 Autodesk 官方推荐格式，但 Blender / Max / Maya / UE
都能正常导入。若目标软件只吃二进制 FBX，可用本工具导出 GLB/OBJ 后
在 Blender 里另存为二进制 FBX（README 有说明）。
"""
from __future__ import annotations

import time
from collections import defaultdict
from pathlib import Path
from typing import Sequence

import numpy as np

from ..mesh import MATERIAL_COLORS, Mesh

FBX_VERSION = 7400


def _fl(v: float) -> str:
    s = f"{v:.6f}".rstrip("0").rstrip(".")
    return s if s not in ("", "-0") else "0"


def _arr(values: Sequence[float]) -> str:
    return ",".join(_fl(v) for v in values)


def export_fbx(
    mesh: Mesh,
    path: str | Path,
    *,
    name: str = "scan2plan",
    up_axis: str = "z",
) -> dict:
    """导出 ASCII FBX。up_axis 仅支持 z（FBX 建筑/产品默认）。"""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    verts = np.asarray(mesh.vertices, dtype=np.float64)
    tri = np.asarray(mesh.faces, dtype=np.int64)
    if len(verts) == 0 or len(tri) == 0:
        raise ValueError("mesh is empty")

    # 面法向
    p0, p1, p2 = verts[tri[:, 0]], verts[tri[:, 1]], verts[tri[:, 2]]
    fn = np.cross(p1 - p0, p2 - p0)
    ln = np.linalg.norm(fn, axis=1, keepdims=True)
    ln[ln < 1e-12] = 1.0
    fn = fn / ln

    by_mat: dict[str, list[int]] = defaultdict(list)
    for fi, m in enumerate(mesh.face_materials):
        by_mat[m].append(fi)

    SCALE = 100.0  # 米 → 厘米（FBX 内定单位）

    def cv(p) -> tuple[float, float, float]:
        return (float(p[0]) * SCALE, float(p[1]) * SCALE, float(p[2]) * SCALE)

    ts = time.localtime()
    stamp = (
        f"{{ Version: 1000 Year: {ts.tm_year} Month: {ts.tm_mon} Day: {ts.tm_mday} "
        f"Hour: {ts.tm_hour} Minute: {ts.tm_min} Second: {ts.tm_sec} Millisecond: 0 }}"
    )
    now = time.strftime("%Y-%m-%d %H:%M:%S")

    geo_ids: list[tuple[str, int]] = []
    model_ids: list[tuple[str, int]] = []
    mat_ids: list[tuple[str, int]] = []
    next_id = 1000000

    out: list[str] = []
    w = out.append
    w("; FBX 7.4.0 project file")
    w("; Generated by scan2plan 0.1 (hand-written ASCII FBX writer, 0 dependencies)")
    w("; ----------------------------------------------------")
    w("")
    w("FBXHeaderExtension:  {")
    w("\tFBXHeaderVersion: 1003")
    w(f"\tFBXVersion: {FBX_VERSION}")
    w(f"\tCreationTimeStamp:  {stamp}")
    w('\tCreator: "scan2plan 0.1"')
    w("\tSceneInfo: \"SceneInfo::GlobalInfo\", \"UserData\" {")
    w("\t\tType: \"UserData\"")
    w(f"\t\tVersion: 100")
    w("\t\tMetaData:  {")
    w("\t\t\tVersion: 100")
    w("\t\t\tTitle: \"scan2plan\"")
    w(f"\t\t\tSubject: \"{name}\"")
    w('\t\t\tAuthor: ""')
    w(f'\t\t\tComment: "units: cm, Z-up; generated {now}"')
    w("\t\t}")
    w("\t}")
    w("}")
    w("")
    w("GlobalSettings:  {")
    w("\tVersion: 1000")
    w("\tProperties70:  {")
    w('\t\tP: "UpAxis", "int", "Integer", "",2')
    w('\t\tP: "UpAxisSign", "int", "Integer", "",1')
    w('\t\tP: "FrontAxis", "int", "Integer", "",1')
    w('\t\tP: "FrontAxisSign", "int", "Integer", "",-1')
    w('\t\tP: "CoordAxis", "int", "Integer", "",0')
    w('\t\tP: "CoordAxisSign", "int", "Integer", "",1')
    w('\t\tP: "OriginalUpAxis", "int", "Integer", "",2')
    w('\t\tP: "OriginalUpAxisSign", "int", "Integer", "",1')
    w('\t\tP: "UnitScaleFactor", "double", "Number", "",1')
    w('\t\tP: "OriginalUnitScaleFactor", "double", "Number", "",1')
    w('\t\tP: "AmbientColor", "ColorRGB", "Color", "",0,0,0')
    w('\t\tP: "DefaultCamera", "KString", "", "", "Producer Perspective"')
    w('\t\tP: "TimeMode", "enum", "", "",11')
    w('\t\tP: "TimeSpanStart", "KTime", "Time", "",0')
    w('\t\tP: "TimeSpanStop", "KTime", "Time", "",46186158000')
    w("\t}")
    w("}")
    w("")
    w("Documents:  {")
    w("\tCount: 1")
    w("\tDocument: 100001, \"\", \"Scene\" {")
    w("\t\tProperties70:  {")
    w('\t\t\tP: "SourceObject", "object", "", ""')
    w('\t\t\tP: "ActiveAnimStackName", "KString", "", "", ""')
    w("\t\t}")
    w("\t\tRootNode: 0")
    w("\t}")
    w("}")
    w("")

    # ---------------- Definitions（先占位，最后回填）
    defs_pos = len(out)
    w("Definitions:  {")
    w("\tVersion: 100")
    w(f"\tCount: {1 + len(by_mat) * 3}")  # GlobalSettings + Geometry/Model/Material
    w('\tObjectType: "GlobalSettings" {')
    w("\t\tCount: 1")
    w("\t}")
    for otype, cnt in (
        ("Geometry", len(by_mat)),
        ("Model", len(by_mat)),
        ("Material", len(by_mat)),
    ):
        w(f'\tObjectType: "{otype}" {{')
        w(f"\t\tCount: {cnt}")
        w("\t}")
    w("}")
    w("")

    # ---------------- Objects
    objects: list[str] = []
    objects.append("Objects:  {")
    for mat in sorted(by_mat):
        fids = by_mat[mat]
        # 顶点收集
        vmap: dict[tuple[float, float, float], int] = {}
        vlist: list[tuple[float, float, float]] = []
        poly_idx: list[int] = []
        normals: list[float] = []
        for fi in fids:
            ia, ib, ic = (int(x) for x in tri[fi])
            for vi in (ia, ib, ic):
                p = cv(verts[vi])
                key = (round(p[0], 5), round(p[1], 5), round(p[2], 5))
                if key not in vmap:
                    vmap[key] = len(vlist)
                    vlist.append(p)
                poly_idx.append(vmap[key])
            n = fn[fi]
            for _ in range(3):
                normals.extend([float(n[0]), float(n[1]), float(n[2])])
        # 每个三角形的最后一个索引取反（FBX 约定）
        for k in range(2, len(poly_idx), 3):
            poly_idx[k] = ~poly_idx[k]

        geo_id = next_id
        next_id += 1
        model_id = next_id
        next_id += 1
        mat_id = next_id
        next_id += 1
        geo_ids.append((mat, geo_id))
        model_ids.append((mat, model_id))
        mat_ids.append((mat, mat_id))

        safe = f"{name}_{mat}".replace(" ", "_")
        # Geometry
        flat_v: list[float] = []
        for p in vlist:
            flat_v.extend(p)
        objects.append(f'\tGeometry: {geo_id}, "Geometry::{safe}", "Mesh" {{')
        objects.append(f"\t\tVertices: *{len(flat_v)} {{")
        objects.append(f"\t\t\ta: {_arr(flat_v)}")
        objects.append("\t\t}")
        objects.append(f"\t\tPolygonVertexIndex: *{len(poly_idx)} {{")
        objects.append("\t\t\ta: " + ",".join(str(i) for i in poly_idx))
        objects.append("\t\t}")
        objects.append("\t\tGeometryVersion: 124")
        objects.append('\t\tLayerElementNormal: 0 {')
        objects.append("\t\t\tVersion: 101")
        objects.append('\t\t\tName: ""')
        objects.append('\t\t\tMappingInformationType: "ByPolygonVertex"')
        objects.append('\t\t\tReferenceInformationType: "Direct"')
        objects.append(f"\t\t\tNormals: *{len(normals)} {{")
        objects.append(f"\t\t\t\ta: {_arr(normals)}")
        objects.append("\t\t\t}")
        objects.append("\t\t}")
        objects.append("\t\tLayer: 0 {")
        objects.append("\t\t\tVersion: 100")
        objects.append("\t\t\tLayerElement:  {")
        objects.append('\t\t\t\tType: "LayerElementNormal"')
        objects.append("\t\t\t\tTypedIndex: 0")
        objects.append("\t\t\t}")
        objects.append("\t\t}")
        objects.append("\t}")
        # Model
        objects.append(f'\tModel: {model_id}, "Model::{safe}", "Mesh" {{')
        objects.append("\t\tVersion: 232")
        objects.append("\t\tProperties70:  {")
        objects.append('\t\t\tP: "DefaultAttributeIndex", "int", "Integer", "",0')
        objects.append('\t\t\tP: "InheritType", "enum", "", "",1')
        objects.append("\t\t}")
        objects.append("\t\tShading: T")
        objects.append('\t\tCulling: "CullingOff"')
        objects.append("\t}")
        # Material
        r, g, b, a = MATERIAL_COLORS.get(mat, (0.8, 0.8, 0.8, 1.0))
        objects.append(f'\tMaterial: {mat_id}, "Material::{safe}", "" {{')
        objects.append("\t\tVersion: 102")
        objects.append('\t\tShadingModel: "phong"')
        objects.append("\t\tMultiLayer: 0")
        objects.append("\t\tProperties70:  {")
        objects.append(
            f'\t\t\tP: "DiffuseColor", "Color", "", "A",{_fl(r)},{_fl(g)},{_fl(b)}'
        )
        objects.append(
            f'\t\t\tP: "AmbientColor", "Color", "", "A",{_fl(r * 0.3)},{_fl(g * 0.3)},{_fl(b * 0.3)}'
        )
        objects.append(
            f'\t\t\tP: "SpecularColor", "Color", "", "A",0.1,0.1,0.1'
        )
        objects.append('\t\t\tP: "Shininess", "double", "Number", "",20')
        objects.append(f'\t\t\tP: "Opacity", "double", "Number", "",{_fl(a)}')
        objects.append("\t\t}")
        objects.append("\t}")
    objects.append("}")
    objects.append("")

    # ---------------- Connections
    objects.append("Connections:  {")
    for (mat, model_id), (mat2, geo_id), (mat3, mat_id) in zip(
        model_ids, geo_ids, mat_ids
    ):
        objects.append(f'\tC: "OO",{geo_id},{model_id}')
        objects.append(f'\tC: "OO",{mat_id},{model_id}')
        objects.append(f'\tC: "OO",{model_id},0')
    objects.append("}")
    objects.append("")

    out.extend(objects)
    text = "\n".join(out) + "\n"
    path.write_text(text, encoding="utf-8-sig")

    return {
        "format": "fbx",
        "variant": "ascii-7.4",
        "path": str(path),
        "bytes": path.stat().st_size,
        "meshes": len(by_mat),
        "materials": sorted(by_mat),
        "triangles": int(len(tri)),
        "unit_scale": "1 fbx unit = 1 cm (model in meters, scaled x100)",
        "up_axis": "z",
    }


def validate_fbx(path: str | Path) -> dict:
    """基本结构校验：括号配对、必需段落、数组长度与声明一致。"""
    raw = Path(path).read_bytes()
    try:
        text = raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        text = raw.decode("utf-8", errors="replace")
    problems: list[str] = []
    depth = 0
    for ch in text:
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth < 0:
                problems.append("花括号提前闭合")
                break
    if depth != 0:
        problems.append(f"花括号不配对（depth={depth}）")
    for need in ("FBXHeaderExtension", "GlobalSettings", "Definitions", "Objects", "Connections"):
        if f"{need}:" not in text:
            problems.append(f"缺少 {need} 段")
    if "FBXVersion: 7400" not in text:
        problems.append("FBXVersion 不是 7400")
    # 数组长度自检
    import re

    for m in re.finditer(r"\*(\d+) \{\s*a: ([^}]*)\}", text):
        declared = int(m.group(1))
        body = m.group(2).strip()
        actual = 0 if not body else len([x for x in body.split(",") if x.strip()])
        if declared != actual:
            problems.append(f"数组声明 {declared} 与实际 {actual} 不符")
    return {
        "ok": not problems,
        "problems": problems,
        "bytes": len(raw),
        "geometries": text.count('"Mesh" {'),
        "materials": text.count('"phong"'),
        "connections": text.count('C: "OO"'),
    }
